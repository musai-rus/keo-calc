const assert=require('node:assert/strict'),A=require('./native-apertures'),S=require('./native-spaces');
const quad=(a,b,c,d)=>[[a,b,c],[a,c,d]],close=(a,b)=>assert(Math.abs(a-b)<1e-8,`${a} != ${b}`);
const face=quad([0,0,0],[3,0,0],[3,2,0],[0,2,0]);
const run=(triangles,unitScale=1)=>A.extract({triangles,unitScale,planarityTolerance:1e-7},S);
let r=run(face);assert.equal(r.status,'patches');assert.equal(r.patches[0].status,'planar-contour');close(r.patches[0].area,6);assert.equal(r.opticsVerified,false);
const rot=p=>[100+p[0]*.6-p[2]*.8,200+p[1],50+p[0]*.8+p[2]*.6];
r=run(face.map(t=>t.map(rot)));close(r.patches[0].area,6);close(r.patches[0].inclinationDeg,53.13010235415599);
r=run(face.map(t=>t.map(p=>p.map(v=>v*1000))),.001);close(r.patches[0].area,6);
assert.deepEqual(run(face.slice().reverse()),run(face));
close(run(face.map(t=>[t[0],t[2],t[1]])).patches[0].area,6);
const hole=[...quad([0,0,0],[4,0,0],[3,1,0],[1,1,0]),...quad([4,0,0],[4,4,0],[3,3,0],[3,1,0]),...quad([4,4,0],[0,4,0],[1,3,0],[3,3,0]),...quad([0,4,0],[0,0,0],[1,1,0],[1,3,0])];
r=run(hole);assert.equal(r.patches[0].status,'planar-contour');close(r.patches[0].area,12);assert.equal(r.patches[0].contours.filter(c=>c.hole).length,1);
const vertical=quad([0,0,0],[0,2,0],[0,2,3],[0,0,3]);r=run(vertical);close(r.patches[0].area,6);close(r.patches[0].inclinationDeg,90);
r=run([...face,...face.map(t=>t.map(p=>[p[0],p[1],p[2]+.02]))]);assert.equal(r.patches.length,2);assert(r.patches.every(p=>p.status==='planar-contour'));
assert.equal(run([...face,face[0]]).reason,'duplicate-triangle');
assert.equal(run([[[0,0,0],[1,0,0],[2,0,0]]]).reason,'degenerate-triangle');
assert.equal(run([...face,[[0,0,0],[3,2,0],[1,1,1]]]).reason,'nonmanifold-edge');
assert.equal(A.extract({triangles:face,unitScale:1},S).reason,'explicit-planarity-tolerance-required');
assert.equal(run(face,NaN).reason,'unknown-units');assert.equal(run([[[NaN,0,0],[1,0,0],[1,1,0]]]).reason,'invalid-triangle');
assert.equal(run([]).reason,'missing-geometry');
console.log('Aperture mesh tests passed: planes, rotation, units, holes, disconnected faces and invalid meshes');
const square=(x,y,w)=>[[x,y],[x+w,y],[x+w,y+w],[x,y+w]],room=[square(0,0,10)];
assert.equal(A.planCoverage([square(1,1,2)],room,S).status,'contained-projection');
assert.equal(A.planCoverage([square(20,20,2)],room,S).status,'outside');
assert.equal(A.planCoverage([square(0,0,2)],room,S).status,'crosses-or-touches-boundary');
assert.equal(A.planCoverage([square(3,3,4)],[...room,square(4,4,2)],S).status,'covers-space-boundary-or-hole');
// Four vertices are inside the concave room but an edge crosses the recess.
const concave=[[[0,0],[10,0],[10,10],[6,10],[6,4],[4,4],[4,10],[0,10]]];
assert.equal(A.planCoverage([[[2,2],[8,2],[8,8],[2,8]]],concave,S).status,'crosses-or-touches-boundary');
assert.equal(A.planCoverage([square(1,1,2)],room,S).ownershipVerified,false);
assert.equal(A.planCoverage([],room,S).status,'unavailable');
console.log('Continuous projection tests passed: concavity, crossings, enclosed holes; no room ownership inferred');
