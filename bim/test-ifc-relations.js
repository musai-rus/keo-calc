const assert=require('node:assert/strict'),R=require('./ifc-relations');
const wrap=s=>"ISO-10303-21;HEADER;FILE_SCHEMA(('IFC4'));ENDSEC;DATA;"+s+'ENDSEC;END-ISO-10303-21;';
const source=`
#1=IFCSPACE('room-a',$,'101',$,$,$,$,'Room A',.ELEMENT.,$,$);
#2=IFCSPACE('room-b',$,'102',$,$,$,$,'Room B',.ELEMENT.,$,$);
#3=IFCWINDOW('window-a',$,'Not a skylight guess',$,$,$,$,$,2.,1.,$,$,$);
#4=IFCOPENINGELEMENT('opening-a',$,$,$,$,$,$,$,$);
#5=IFCWALL('wall-a',$,$,$,$,$,$,$,$);
#6=IFCRELFILLSELEMENT('fill-a',$,$,$,#4,#3);
#7=IFCRELVOIDSELEMENT('void-a',$,$,$,#5,#4);
#8=IFCRELSPACEBOUNDARY('boundary-a',$,$,$,#1,#3,#999,.PHYSICAL.,.EXTERNAL.);
#9=IFCCURTAINWALL('curtain-a',$,'Opaque or glass unknown',$,$,$,$,$,$);
#10=IFCPLATE('panel-a',$,$,$,$,$,$,$,$);
#11=IFCRELAGGREGATES('agg-a',$,$,$,#9,(#10));
#12=IFCRELSPACEBOUNDARY('boundary-b',$,$,$,#1,#9,$,.PHYSICAL.,.INTERNAL.);
#13=IFCRELSPACEBOUNDARY('boundary-c',$,$,$,#2,#9,$,.PHYSICAL.,.INTERNAL.);
#14=IFCPROPERTYSINGLEVALUE('IsExternal',$,IFCBOOLEAN(.T.),$);
#15=IFCPROPERTYSET('pset-a',$,'Pset_WindowCommon',$,(#14));
#16=IFCRELDEFINESBYPROPERTIES('prop-rel',$,$,$,(#3),#15);
#17=IFCWINDOWTYPE('window-type',$,'Synthetic window type',$,$,$,$,$,$,$,$,$,$);
#18=IFCRELDEFINESBYTYPE('type-rel',$,$,$,(#3),#17);
`;
const get=s=>R.analyze(R.parse(wrap(s)));
const r=get(source),w=r.candidates.find(c=>c.guid==='window-a'),p=r.candidates.find(c=>c.guid==='panel-a');
assert.equal(r.spaces.length,2);assert.equal(w.hosts[0].host.guid,'wall-a');assert.equal(w.hosts[0].opening.guid,'opening-a');
assert.equal(w.declaredBoundaries[0].space.guid,'room-a');assert.equal(w.declaredBoundaries[0].exposure,'EXTERNAL');
assert.equal(w.properties[0].value.values[0].enum,'T');assert.equal(w.ownershipVerified,false);assert.equal(w.opticsVerified,false);
assert.equal(w.declaredType.guid,'window-type');assert.equal(w.declaredType.name,'Synthetic window type');
assert.equal(p.kind,'curtain-panel');assert.equal(p.declaredBoundaries.length,0);assert.equal(p.containerBoundaries.length,2);assert.equal(p.ownershipVerified,false);
assert.deepEqual(get(source.split('\n').reverse().join('\n')).candidates,r.candidates);
assert.equal(R.values("('a;#1=IFCSPACE(''fake'');',#12,(1.,-2.E-3),.T.,$,*,IFCLABEL('x'))")[0],"a;#1=IFCSPACE('fake');");
assert.equal(R.values("('\\X2\\041A0415041E\\X0\\')")[0],'КЕО');
assert.equal(R.parse(wrap("/* ; #900=x */ #1=IFCSPACE /* comment */ ('x',$,$,$,$,$,$,$,$,$,$);" )).records.get(1).args[0],'x');
assert.throws(()=>R.parse(wrap(source+'#3=IFCWALL($);')),/duplicate/);
assert.throws(()=>R.parse(wrap(source+'#50=IFCUNKNOWN($);#50=IFCUNKNOWN($);')),/duplicate/);
assert.throws(()=>R.parse(wrap(source).replace('IFC4','IFC2X3')),/schema/);
assert.throws(()=>R.parse(wrap(source).slice(0,-5)),/incomplete/);
assert.throws(()=>R.values('(1e999)'),/nonfinite/);
assert.throws(()=>R.values("('unterminated)"),/unterminated/);
assert(get(source.replace('#1,#3,#999','#400,#3,#999')).issues.some(i=>i.code==='missing-or-wrong-reference'));
assert(get(source.replace("'room-b'","'room-a'")).issues.some(i=>i.code==='duplicate-guid'));
assert(get(source+"#40=IFCRELFILLSELEMENT('extra',$,$,$,#4,#3);").candidates.find(c=>c.guid==='window-a').reasons.includes('ambiguous-opening-host'));
assert(get(source+"#41=IFCRELAGGREGATES('cycle',$,$,$,#10,(#9));").candidates.find(c=>c.guid==='panel-a').reasons.includes('cyclic-decomposition'));
assert.equal(get(source.replace('IFCWINDOW(', 'IFCDOOR(')).candidates.find(c=>c.guid==='window-a').kind,'door');
assert.equal(get(source.replace('IFCWINDOWTYPE(', 'IFCPLATETYPE(')).candidates.find(c=>c.guid==='window-a').declaredType,null);
assert.equal(get(source+"#42=IFCRELDEFINESBYTYPE('duplicate-type',$,$,$,(#3),#17);").candidates.find(c=>c.guid==='window-a').declaredType,null);
console.log('IFC relation tests passed: syntax, references, identity, graph, no optical/ownership claims');
