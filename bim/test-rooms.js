const assert=require('assert/strict'),fs=require('fs'),R=require('./rooms.js');
const G=new Function(fs.readFileSync(__dirname+'/geom.js','utf8')+';return BimGeom;')();
const box=(x,y,w,h)=>[[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
const room=(key,loops)=>({key,externalId:key,level:'L01',area:16,geometry:{segments:R.segments(loops),source:'test'}});
const grid={W:120,H:80,cell:.1,minx:0,miny:0,lab:new Int32Array(9600).fill(1),regs:[null,{id:1}],ext:new Set()};
const a=room('a',[box(1,1,4,4)]),b=room('b',[box(6,1,4,4)]);
assert.deepEqual(R.section(a.geometry.segments,[2,2],[1,0]),[3,1]);
let q=R.raster(grid,[a,b],()=>false);
assert.equal(q.spaces.length,2);assert.equal(q.spaces[0].rooms.length,1);
assert.ok(Math.abs(q.R.regs[1].areaC-16)<1e-8);
assert.equal(q.lab[20*120+55],-1,'нет роста в промежуток');
q=R.raster(grid,[b,a],()=>false);
assert.equal(q.spaces[q.lab[20*120+20]].key,'a','одинаковые площади и порядок Room не меняют привязку');
const hole=room('hole',[box(1,1,4,4),box(2,2,1,1)]);
q=R.raster(grid,[hole],()=>false);assert.equal(q.lab[25*120+25],-1);assert.ok(Math.abs(q.R.regs[1].areaC-15)<1e-8);
assert.equal(R.footprint(q.R,q.lab,box(1.5,1.5,2,2)).space,-1,'отверстие Room внутри фонаря исключает привязку');
assert.equal(R.footprint(q.R,q.lab,box(3.2,3.2,.5,.5)).space,0);
const concave=room('L',[[[1,1],[5,1],[5,2],[2,2],[2,5],[1,5]]]);
q=R.raster(grid,[concave],()=>false);assert.ok(Math.abs(q.R.regs[1].areaC-7)<1e-8);
q=R.raster(grid,[room('a',[box(1,1,4,4)]),room('b',[box(2,2,4,4)])],()=>false);assert.equal(q.spaces.length,0,'перекрывающиеся Room не получают результат');
assert.equal(R.raster(grid,[{key:'x',area:16}],()=>false).spaces.length,0,'по площади не подбираем');
assert.equal(R.closed([[0,0,1,0],[1,0,1,1]]),false);
const data={version:1,model:'m',coordinates:'viewer-metres',rooms:[{externalId:'a',level:'L01',loops:[box(1,1,4,4)]}]};
assert.equal(R.importData(data,'m',[a]).size,1);
assert.throws(()=>R.importData(data,'other',[a]),/модели/);
assert.throws(()=>R.importData({...data,rooms:[...data.rooms,...data.rooms]},'m',[a]),/повторяется/);
assert.throws(()=>R.importData({...data,rooms:[{...data.rooms[0],externalId:'wrong'}]},'m',[a]),/не найден/);
assert.throws(()=>R.segments([[[0,0],[NaN,1],[2,2]]]),/Некорректный/);
assert.equal(G.apertureShape(box(0,0,2,2)).shape,'rect','квадрат не круг');
const rotation=box(0,0,2,4).map(([x,y])=>[(x-y)/Math.sqrt(2),(x+y)/Math.sqrt(2)]);
const rotated=G.apertureShape(rotation);assert.equal(rotated.shape,'rect');assert.ok(Math.abs(rotated.av*rotated.bv-8)<1e-8);
const circle=Array.from({length:48},(_,i)=>[Math.cos(i*Math.PI/24),Math.sin(i*Math.PI/24)]);
assert.equal(G.apertureShape(circle.concat([[0,0]])).shape,'round');
assert.equal(G.apertureShape(circle.map(([x,y])=>[2*x,y])).shape,'other','эллипс не круг');
assert.equal(G.apertureShape([[0,0],[2,0],[1,1]]).shape,'other','треугольник не прямоугольник');
console.log('OK: Room identity, equal areas, holes, concavity, overlap, missing geometry, import validation; square, rotated rectangle, circle, ellipse, triangle');
