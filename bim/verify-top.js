/* Независимая оценка прямой составляющей верхнего света (Б.3) — границы для εв по ядру.
   Ядро: εв = 100·Aф.в/(π·hр²)·q(γ)·cos^m(α), m = 2 + 2/Kc (точечный источник, шахта учтена через Kc; круглый фонарь — (8.3)).
   Здесь — численное интегрирование с моделью неба (3.2) q(γ) = 0,429·[1 + 4·exp(−0,7/sin γ)]:
     «отверстие без шахты» — верхнее отверстие ⌀D1 на отметке потолка (верхняя граница прямого света);
     «через шахту» — лучи, проходящие и нижнее отверстие ⌀D2 (потолок), и верхнее ⌀D1 (hс.ф выше), без отражений
     от стенок шахты (нижняя граница).
   Ожидаемо: через шахту ≤ ядро; ядро ≈ без шахты; под фонарём ядро может быть выше — формула Б.3 считает отверстие
   точечным с яркостью зенита.
   Данные — помещение 71 «Спальня», модель 1226, уровень L01 (КЕО по модели, 09.10.2026): hр = 4,2 м (УРП — пол),
   фонари A_GMO_Skywindow_Angle круглые, D1 = Diameter_Inside (верх), D2 = Diameter_Bottom (низ).
   Запуск: node bim/verify-top.js */
const q = sg => sg <= 0 ? 0.429 : 0.429 * (1 + 4 * Math.exp(-0.7 / sg));
function eps(P, L, d1, d2, hr, hsf, shaft, n = 400) {
  // интегрирование по кругу: без шахты — ⌀d1 на отметке hr; через шахту — по нижнему ⌀d2 с проверкой прохода через верхний ⌀d1
  const R = (shaft ? d2 : d1) / 2, r1 = d1 / 2, d = 2 * R / n; let s = 0;
  for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) {
    const ox = -R + (i + 0.5) * d, oy = -R + (j + 0.5) * d; if (ox * ox + oy * oy > R * R) continue;
    const x = L.x + ox, y = L.y + oy, dx = x - P.x, dy = y - P.y, r2 = dx * dx + dy * dy + hr * hr, r = Math.sqrt(r2);
    if (shaft) { const k = hsf / hr, X = ox + dx * k, Y = oy + dy * k; if (X * X + Y * Y > r1 * r1) continue; }
    s += q(hr / r) * hr * hr / (r2 * r2);
  }
  return 100 * s * d * d / Math.PI;
}
