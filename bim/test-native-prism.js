const assert=require('node:assert/strict'),P=require('./native-prism');
const quad=(a,b,c,d)=>[[a,b,c],[a,c,d]],square=(x,y,w)=>[[x,y],[x+w,y],[x+w,y+w],[x,y+w]];
const prism={polygon:square(0,0,2),zMin:0,zMax:5};
const run=(triangles,p=prism,scale=1)=>P.build({meshes:[{id:'surface',triangles}],unitScale:scale}).test(p);
const slab=quad([-1,-1,2],[3,-1,2],[3,3,2],[-1,3,2]);
assert.equal(run(slab).status,'intersected');
assert.equal(run(slab,{...prism,zMin:3,zMax:5}).status,'no-intersection-in-supplied-meshes');
assert.equal(run(slab,{...prism,zMin:0,zMax:2}).status,'contact-only');
// Small rib misses the centre ray but intersects the full aperture column.
assert.equal(run(quad([.1,.1,1],[.2,.1,1],[.2,.2,1],[.1,.2,1])).status,'intersected');
assert.equal(run(quad([1,-1,1],[1,3,1],[1,3,4],[1,-1,4])).status,'intersected');
assert.equal(run(quad([0,-1,1],[0,3,1],[0,3,4],[0,-1,4])).status,'contact-only');
const roofHole=[...quad([-1,-1,2],[3,-1,2],[3,-.1,2],[-1,-.1,2]),...quad([-1,2.1,2],[3,2.1,2],[3,3,2],[-1,3,2]),...quad([-1,-.1,2],[-.1,-.1,2],[-.1,2.1,2],[-1,2.1,2]),...quad([2.1,-.1,2],[3,-.1,2],[3,2.1,2],[2.1,2.1,2])];
assert.equal(run(roofHole).status,'no-intersection-in-supplied-meshes');
assert.equal(run([...roofHole,...slab]).status,'intersected');
const moved=p=>[20+p[0]*.6-p[1]*.8,-40+p[0]*.8+p[1]*.6,100+p[2]];
assert.equal(run(slab.map(t=>t.map(moved)),{polygon:prism.polygon.map(p=>moved([...p,0]).slice(0,2)),zMin:100,zMax:105}).status,'intersected');
assert.equal(run(slab.map(t=>t.map(p=>p.map(v=>v*1000))),prism,.001).status,'intersected');
assert.deepEqual(run(slab.slice().reverse()).hits,run(slab).hits);
assert.equal(run(slab,{...prism,polygon:prism.polygon.slice().reverse()}).status,'intersected');
assert.equal(run(slab,{...prism,polygon:[[0,0],[2,0],[1,1],[2,2],[0,2]]}).reason,'nonconvex-or-crossing-footprint');
assert.equal(run(slab,{...prism,polygon:[[0,0],[2,2],[0,2],[2,0]]}).status,'unavailable');
assert.equal(run(slab,{...prism,polygon:[...prism.polygon,...prism.polygon]}).reason,'duplicate-or-unstable-footprint-vertex');
assert.equal(run(slab,{...prism,zMin:5}).status,'unavailable');
assert.equal(run(slab,{...prism,maxClipOperations:1}).reason,'prism-clipping-resource-limit');
assert.equal(run(slab).ownershipVerified,false);
assert.throws(()=>P.build({meshes:[],unitScale:1}));
assert.throws(()=>P.build({meshes:[{id:'x',triangles:[]}],unitScale:1}));
const collapsed=[[[.1,.1,1],[.2,.1,1],[.3,.1,1]]];
assert.equal(run(collapsed).reason,'degenerate-source-triangles');
assert.equal(run(collapsed).status,'unavailable');
assert.equal(run([...slab,...collapsed]).status,'intersected');
assert.equal(run([...slab,...collapsed]).uncertainTriangles,1);
assert.equal(run(collapsed,{...prism,polygon:square(10,10,2)}).status,'no-intersection-in-supplied-meshes');
assert.throws(()=>run([[[Infinity,0,0],[1,0,0],[2,1,0]]]));
assert.throws(()=>run(slab,prism,NaN));
const A=require('./native-projected-area');
assert.equal(A.remainder({footprint:[...prism.polygon,...prism.polygon],cutters:[]}).reason,'duplicate-or-unstable-footprint-vertex');
const projected=triangles=>P.build({meshes:[{id:'surface',triangles}],unitScale:1},A).test(prism);
assert.equal(projected(slab).coverage.remainingArea,0);
assert.ok(Math.abs(projected(roofHole).coverage.remainingArea-4)<1e-9);
assert.ok(Math.abs(projected(quad([.1,.1,1],[.2,.1,1],[.2,.2,1],[.1,.2,1])).coverage.remainingArea-3.99)<1e-8);
assert.ok(Math.abs(projected(quad([1,-1,1],[1,3,1],[1,3,4],[1,-1,4])).coverage.remainingArea-4)<1e-8);
assert.equal(projected(collapsed).coverage.status,'unavailable');
// No boundary crossing can also mean that the whole prism is INSIDE a solid.
// The API deliberately does not convert this into a clear/light-path verdict.
const shell=[...quad([-1,-1,-1],[3,-1,-1],[3,3,-1],[-1,3,-1]),...quad([-1,-1,6],[3,-1,6],[3,3,6],[-1,3,6]),...quad([-1,-1,-1],[-1,3,-1],[-1,3,6],[-1,-1,6]),...quad([3,-1,-1],[3,3,-1],[3,3,6],[3,-1,6]),...quad([-1,-1,-1],[3,-1,-1],[3,-1,6],[-1,-1,6]),...quad([-1,3,-1],[3,3,-1],[3,3,6],[-1,3,6])];
assert.equal(projected(shell).status,'no-intersection-in-supplied-meshes');
assert.equal(projected(shell).geometryVerified,false);
console.log('Continuous prism tests passed: roof hole, small rib, vertical walls, contact, units, transforms, invalid geometry; no ownership inferred');
