const assert=require('node:assert/strict'),R=require('./ifc-relations'),M=require('./ifc-material-parts');
const source=`
#1=IFCSLAB('host',$,$,$,$,$,#2,$,$);
#2=IFCPRODUCTDEFINITIONSHAPE($,$,(#3));
#3=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#4,#5));
#4=IFCEXTRUDEDAREASOLID($,$,$,600.);
#5=IFCEXTRUDEDAREASOLID($,$,$,100.);
#6=IFCSHAPEASPECT((#8),'part-a',$,.U.,#2);
#7=IFCSHAPEASPECT((#9),'part-b',$,.U.,#2);
#8=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#4));
#9=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#5));
#10=IFCRELASSOCIATESMATERIAL('rel',$,$,$,(#1),#11);
#11=IFCMATERIALCONSTITUENTSET($,$,(#12,#13));
#12=IFCMATERIALCONSTITUENT('part-a',$,#14,0.85,$);
#13=IFCMATERIALCONSTITUENT('part-b',$,#15,0.15,$);
#14=IFCMATERIAL('arbitrary-one',$,'Gas');
#15=IFCMATERIAL('arbitrary-two',$,$);
`;
function index(s=source){return R.parse("ISO-10303-21;HEADER;FILE_SCHEMA(('IFC4'));ENDSEC;DATA;"+s+'ENDSEC;END-ISO-10303-21;',new Set([...R.TYPES,...M.TYPES]));}
const get=s=>M.analyze(index(s),['host']).elements[0];
const e=get();assert.equal(e.status,'diagnostic');assert.equal(e.parts.length,2);
assert.deepEqual(e.parts.map(p=>[p.itemIds,p.material.name,p.physicalRole]),[[[4],'arbitrary-one','unspecified'],[[5],'arbitrary-two','unspecified']]);
assert.deepEqual(e.unassignedBodyItemIds,[]);assert.equal(e.parts[0].productDefinitional,'U');
const matched=M.matchViewer(e,{aspectName:'part-a',materialName:'arbitrary-one'});
assert.equal(matched.status,'declared-material-match');assert.equal(matched.sourceMaterialMatched,true);
for(const key of ['geometryVerified','opticsVerified','normativeVerified','revisionVerified'])assert.equal(matched[key],false);
assert.equal(matched.physicalRole,'unspecified');
assert.equal(M.matchViewer(e,{aspectName:'part-a',materialName:'arbitrary-two'}).reason,'viewer-material-does-not-match-source');
assert.equal(M.matchViewer(e,{aspectName:'PART-A',materialName:'arbitrary-one'}).reason,'missing-source-aspect-name');
assert.equal(M.matchViewer(e,{aspectName:'part-a',materialName:null}).status,'unavailable');
assert.equal(get(source.replace("'part-a',$,#14","'different',$,#14")).parts[0].reason,'missing-constituent-keyword');
assert.equal(get(source.replace("'part-b',$,#15","'part-a',$,#15")).parts[0].reason,'ambiguous-constituent-keyword');
assert.equal(get(source.replace('#14,0.85','#999,0.85')).parts[0].reason,'missing-material-record');
assert.equal(get(source.replace("#8=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#4))","#8=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#999))")).parts[0].reason,'aspect-items-not-in-current-body');
const overlap=get(source.replace("#9=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#5))","#9=IFCSHAPEREPRESENTATION($,'Body','SweptSolid',(#4))"));
assert(overlap.parts.every(p=>p.reason==='overlapping-shape-aspects'&&!p.sourceMaterialMatched));
assert.equal(get(source.replace("'part-b',$,.U.,#2","'part-a',$,.U.,#2")).parts.length,2);
assert.equal(M.matchViewer(get(source.replace("'part-b',$,.U.,#2","'part-a',$,.U.,#2")),{aspectName:'part-a',materialName:'arbitrary-one'}).reason,'ambiguous-source-aspect-name');
assert.equal(get(source.replace('IFCMATERIALCONSTITUENTSET','IFCMATERIALLAYERSET')).reason,'unsupported-material-definition');
assert.equal(get(source.replaceAll(".U.,#2)",".U.,#999)")).reason,'missing-direct-shape-aspects');
assert.equal(get(source.replace("#10=IFCRELASSOCIATESMATERIAL('rel',$,$,$,(#1),#11);",'')).reason,'missing-material-association');
assert.equal(get(source+"#20=IFCRELASSOCIATESMATERIAL('other',$,$,$,(#1),#21);").reason,'ambiguous-material-association');
assert.equal(get(source+"#20=IFCSLAB('host',$,$,$,$,$,#2,$,$);").reason,'missing-or-duplicate-element-guid');
const typed=source.replace('(#1),#11','(#20),#11')+"#20=IFCSLABTYPE('type',$,$,$,$,$,$,$,$,$);#21=IFCRELDEFINESBYTYPE('typed',$,$,$,(#1),#20);";
assert.equal(get(typed).parts.filter(p=>p.sourceMaterialMatched).length,2);
assert.equal(get(typed+"#22=IFCRELDEFINESBYTYPE('duplicate',$,$,$,(#1),#20);").reason,'ambiguous-declared-type');
assert.deepEqual(get(source.split('\n').reverse().join('\n')).parts.sort((a,b)=>a.aspectId-b.aspectId),e.parts);
assert.throws(()=>M.analyze(index(),['host','host']),/invalid/);
assert.throws(()=>M.analyze(null,['host']),/invalid/);
console.log('IFC material part tests passed: declared links, ambiguity, source/viewer mismatch, no optical inference');
